    public void CargarProveedor(){
    
      DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("Id");
    modelo.addColumn("Nombre");
    modelo.addColumn("Nombre de Empresa");
    modelo.addColumn("Dirección");
    modelo.addColumn("Telefono");

   
    
    Tabla_Proveedor.setModel(modelo);  
    
     try {
        Connection con = Conexion.conectar();
        String sql = "SELECT id,Nombre,Nombre_Empresa,Direccion, Telefono FROM Proveedores";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            Object[] fila = new Object[5];
            fila[0] = rs.getInt("id");
            fila[1] = rs.getString("Nombre");
            fila[2]=rs.getString("Nombre_Empresa");
            fila[3] = rs.getString("Direccion");
            fila[4] = rs.getString("Telefono");

            modelo.addRow(fila);
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar proveedores: " + e.getMessage());
    }
    
    }
