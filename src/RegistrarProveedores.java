public void Registrar(){
  
String nombre=Nombre_Proveedor.getText();
String NombreEmpresa=Nombre_Empresa.getText();
        String telefono=Telefono_Proveedor.getText();
        String Dirección=Dirección_Proveedor.getText();
        
        if(nombre.isEmpty() || NombreEmpresa.isEmpty()|| telefono.isEmpty() || Dirección.isEmpty()){
         JOptionPane.showMessageDialog(this, "Llena todo los datos");
         return;
    }
        try{
        Connection con = Conexion.conectar();

        String sql = "INSERT INTO proveedores(nombre, telefono, direccion, Nombre_Empresa) VALUES (?,?,?,?)";
        PreparedStatement ps = con.prepareStatement(sql);
        
        ps.setString(1, nombre);
        ps.setString(2, telefono);
        ps.setString(3, Dirección);
        ps.setString(4, NombreEmpresa);
        
        
        
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this, "Proveedor registrado con éxito");

        // Limpiar campos
       
        Nombre_Proveedor.setText("");
        Telefono_Proveedor.setText("");
        Dirección_Proveedor.setText("");
        Nombre_Empresa.setText("");

        con.close();
        }catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }

}
