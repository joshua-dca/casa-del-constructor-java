    // Método para llenar el ComboBox con los nombres de la tabla productos
    public void CargarProducto() {
        try (Connection con = Conexion.conectar();
             PreparedStatement ps = con.prepareStatement("SELECT nombre FROM productos");
             ResultSet rs = ps.executeQuery()) {

            Producto_caja.removeAllItems();
            while (rs.next()) {
                Producto_caja.addItem(rs.getString("nombre"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar productos: " + e.getMessage());
        }
    }

    // Método que se activa al cambiar de producto en el ComboBox
    public void mostrarStockActual() {
        if (Producto_caja.getSelectedItem() == null) return;

        String seleccionado = Producto_caja.getSelectedItem().toString();

        try (Connection con = Conexion.conectar()) {
            PreparedStatement ps = con.prepareStatement("SELECT cantidad FROM productos WHERE id_producto = ?");
            ps.setString(1, seleccionado);
            ResultSet rs = ps.executeQuery();

            if (rs.next()) {
                int stock = rs.getInt("cantidad");
                Stock_producto.setText("Stock disponible: " + stock);
                
                // Alerta visual: Rojo si no hay nada, Negro si hay
                if (stock <= 0) {
                    Stock_producto.setForeground(Color.RED);
                } else {
                    Stock_producto.setForeground(Color.BLACK);
                }
            }
        } catch (Exception e) {
            System.err.println("Error al consultar stock: " + e.getMessage());
        }
    }

    // Método para guardar el precio de venta (UPDATE)
    public void RegistrarPrecioVenta() {
        if (Precio_producto.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor, asigna un precio de venta.");
            return;
        }

        String nombreProd = Producto_caja.getSelectedItem().toString();
        double precioVenta;

        try {
            precioVenta = Double.parseDouble(Precio_producto.getText());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El precio debe ser un número válido.");
            return;
        }

        try (Connection con = Conexion.conectar()) {
            // Actualizamos el precio en la tabla productos
            // El stock no se toca aquí porque ya se sumó en la Compra
            PreparedStatement ps = con.prepareStatement("UPDATE productos SET precio = ? WHERE nombre = ?");
            ps.setDouble(1, precioVenta);
            ps.setString(2, nombreProd);

            int exito = ps.executeUpdate();
            if (exito > 0) {
                JOptionPane.showMessageDialog(this, "¡Precio de venta actualizado para " + nombreProd + "!");
                Precio_producto.setText("");
                Stock_producto.setText(""); // Si usas este campo para algo más
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
        }
    }
