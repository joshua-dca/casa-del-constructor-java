    public void AgregarEmpleado(){
        
    String nombre= nombre_empleado.getText();
        String apellido=apellidos_empleado.getText();
        String contraseña=contrasena_empleado.getText();
        String rol=rol_empleado.getText();
        String permisos=permisos_empleado.getText();
        
        if(nombre.isEmpty() ||  apellido.isEmpty()  || contraseña.isEmpty() ||  rol.isEmpty()|| permisos.isEmpty()){
         JOptionPane.showMessageDialog(this, "Llena todo los datos");
         return;
    }
        try{
        Connection con = Conexion.conectar();

        String sql = "INSERT INTO empleados(nombre,apellidos, rol, contrasena, permisos) VALUES (?, ?, ?,?,?)";
        PreparedStatement ps = con.prepareStatement(sql);

       
        ps.setString(1, nombre);
        ps.setString(2, apellido);
        ps.setString(3, rol);
        ps.setString(4, contraseña);
        ps.setString(5, permisos);
        
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this, "Empleado registrado con éxito");

        // Limpiar campos

        nombre_empleado.setText("");
        apellidos_empleado.setText("");
        rol_empleado.setText("");
        contrasena_empleado.setText("");
        permisos_empleado.setText("");

        con.close();
        }catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }
