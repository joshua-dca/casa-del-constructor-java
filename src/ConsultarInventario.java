    public void Inventario(){
     DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("Id_producto");
    modelo.addColumn("Nombre");
    modelo.addColumn("Precio");
    modelo.addColumn("cantidad");
    
    
    Tabla_Inventario.setModel(modelo);
    
      try {
        Connection con = Conexion.conectar();
        String sql = "SELECT id_producto,nombre,precio,cantidad FROM productos";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            Object[] fila = new Object[4];
            fila[0] = rs.getInt("Id_producto");
            fila[1]= rs.getString("Nombre");
            fila[2] = rs.getString("Precio");
            fila[3] = rs.getString("cantidad");
            
            
            modelo.addRow(fila);
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar empleados: " + e.getMessage());
    }
    
    
    }
    
    public void actualizarTablaInventario() {
    DefaultTableModel modeloInventario = (DefaultTableModel) Tabla_Inventario.getModel();
    modeloInventario.setRowCount(0); // Limpiamos la tabla actual

    try (Connection con = Conexion.conectar()) {
        String sql = "SELECT id_producto, nombre, precio, cantidad FROM productos";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            Object[] fila = new Object[4];
            fila[0] = rs.getInt("id_producto");
            fila[1] = rs.getString("nombre");
            fila[2] = rs.getDouble("precio");
            fila[3] = rs.getInt("cantidad");
            modeloInventario.addRow(fila);
        }
    } catch (Exception e) {
        System.err.println("Error al actualizar tabla: " + e.getMessage());
    }
}
