    private void cargarEmpleados(){
    
      DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("ID");
    modelo.addColumn("Nombre");
    modelo.addColumn("Apellidos");
    modelo.addColumn("Rol");
    modelo.addColumn("Contrasena");
    modelo.addColumn("permisos");
    modelo.addColumn("Estado");
    
    TablaEliminar.setModel(modelo);  
    
     try {
        Connection con = Conexion.conectar();
        String sql = "SELECT id, nombre, apellidos, rol , contrasena,permisos, Estado FROM empleados";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            Object[] fila = new Object[7];
            fila[0] = rs.getInt("id");
            fila[1] = rs.getString("nombre");
            fila[2] = rs.getString("apellidos");
            fila[3] = rs.getString("rol");
            fila[4]= rs.getString("Contrasena");
            fila[5] = rs.getString("permisos");
            fila[6]= rs.getString("Estado");

            modelo.addRow(fila);
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar empleados: " + e.getMessage());
    }
    
    }
    
