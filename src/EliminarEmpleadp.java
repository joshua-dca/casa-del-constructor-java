    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        int fila = TablaEliminar.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, "Selecciona un proveedor");
        return;
    }

    int idEmpleado = Integer.parseInt(
        TablaEliminar.getValueAt(fila, 0).toString()
    );

    int opcion = JOptionPane.showConfirmDialog(
        this,
        "¿Seguro que deseas borrar al proveedor?",
        "Confirmar",
        JOptionPane.YES_NO_OPTION
    );

    if (opcion == JOptionPane.YES_OPTION) {
        try {
            Connection con = Conexion.conectar();
            PreparedStatement ps = con.prepareStatement(
                "DELETE FROM Empleados WHERE id = ?"
            );
            ps.setInt(1, idEmpleado);
            ps.executeUpdate();
            con.close();

            cargarEmpleados(); // refresca la tabla

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    }//GEN-LAST:event_jButton2ActionPerformed


