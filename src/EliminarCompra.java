public void cargarConsulta(){

DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("ID Compra");
    modelo.addColumn("Fecha");
    modelo.addColumn("Proveedor");
    modelo.addColumn("Productos (Cant)");
    modelo.addColumn("Total Compra");

    // Asigna el nombre de tu tabla del JFrame aquí
    Tabla_compra.setModel(modelo);

    // SQL Corregido para la tabla de COMPRAS
    String sql = "SELECT c.id_compra, c.fecha, c.proveedor, " +
                 "GROUP_CONCAT(CONCAT(p.nombre, ' (', dc.cantidad, ')') SEPARATOR ', ') as lista, " + 
                 "SUM(dc.cantidad * dc.precio_compra) as total " +
                 "FROM compras c " +
                 "JOIN detalle_compra dc ON c.id_compra = dc.id_compra " +
                 "JOIN productos p ON dc.id_producto = p.nombre " + 
                 "GROUP BY c.id_compra, c.fecha, c.proveedor";

    try (Connection con = Conexion.conectar();
         PreparedStatement ps = con.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            Object[] fila = new Object[5];
            fila[0] = rs.getInt("ID_compra");
            fila[1] = rs.getString("Fecha");
            fila[2] = rs.getString("proveedor");
            fila[3] = rs.getString("lista");
            fila[4] = rs.getDouble("total");
            
            modelo.addRow(fila);
        }
        
        // Ajustar ancho de la columna de productos para que se lea bien
        Tabla_compra.getColumnModel().getColumn(3).setPreferredWidth(300);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al consultar compras: " + e.getMessage());
    }

}
