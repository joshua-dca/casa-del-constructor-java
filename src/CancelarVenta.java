  public void cargarConsultaVentasResumida() {
    DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("ID Venta");
    modelo.addColumn("Fecha");
    modelo.addColumn("Cliente");
    modelo.addColumn("Detalle (Cant)"); // <--- Aquí saldrá: Producto (X)
    modelo.addColumn("Total");
    modelo.addColumn("Estado");

    TablaVentas.setModel(modelo);
TablaVentas.getColumnModel().getColumn(3).setPreferredWidth(200);
    // SQL que concatena nombre y cantidad dentro del GROUP_CONCAT
    String sql = "SELECT v.id_ventas, v.Fechas, c.nombre_cliente, v.estado, " +
                 "GROUP_CONCAT(CONCAT(p.nombre, ' (', dv.cantidad, ')') SEPARATOR ', ') as detalle_productos, " + 
                 "SUM(dv.cantidad * dv.precio_unitario) as total_acumulado " +
                 "FROM ventas v " +
                 "JOIN clientes c ON v.id_cliente = c.id_cliente " +
                 "JOIN detalle_ventas dv ON v.id_ventas = dv.id_ventas " +
                 "JOIN productos p ON dv.id_producto = p.id_producto " +
                 "GROUP BY v.id_ventas, v.Fechas, c.nombre_cliente, v.estado";

    try (Connection con = Conexion.conectar();
         PreparedStatement ps = con.prepareStatement(sql);
         ResultSet rs = ps.executeQuery()) {

        while (rs.next()) {
            Object[] fila = new Object[6];
            fila[0] = rs.getInt("id_ventas");
            fila[1] = rs.getString("Fechas");
            fila[2] = rs.getString("nombre_cliente");
            fila[3] = rs.getString("detalle_productos"); // "Martillo (2), Clavos (10)"
            fila[4] = rs.getDouble("total_acumulado");
            fila[5] = rs.getString("estado");
            
            modelo.addRow(fila);
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}
