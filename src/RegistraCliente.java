    public void cliente(){

String Nombre=nombre_cliente.getText();
String Dirección=dirección_cliente.getText();
String telefono=telefono_cliente.getText();
String correo=correo_cliente.getText();
        
        if(Nombre.isEmpty() || Dirección.isEmpty()|| telefono.isEmpty()|| correo.isEmpty()){
         JOptionPane.showMessageDialog(this, "Llena todo los datos");
         return;
    }
        try{
        Connection con = Conexion.conectar();

        String sql = "INSERT INTO clientes (nombre_cliente, dirección_cliente, telefono_cliente, correo_cliente) VALUES (?,?,?,?)";
        PreparedStatement ps = con.prepareStatement(sql);
        
        ps.setString(1, Nombre);
        ps.setString(2, Dirección);
        ps.setString(3, telefono);
        ps.setString(4, correo);
       
        ps.executeUpdate();

        JOptionPane.showMessageDialog(this, "Cliente registrado con éxito");

        // Limpiar campos
      
        nombre_cliente.setText("");
        dirección_cliente.setText("");
        telefono_cliente.setText("");
        correo_cliente.setText("");
        

        con.close();
        }catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }

    }
