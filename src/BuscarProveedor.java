   public void Buscar(){
   String Nombre= Nombre_Proveedor.getText();
   
   if (Nombre.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingresa un Nombre");
        return;
    }

    DefaultTableModel modelo = (DefaultTableModel) Tabla_Buscar.getModel();
    modelo.setRowCount(0);


    try {
        Connection con = Conexion.conectar();

        String sql = "SELECT id, Nombre, Nombre_Empresa FROM proveedores where Nombre=?";

        PreparedStatement ps = con.prepareStatement(sql);

        ps.setString(1,Nombre); 
       

        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            modelo.addRow(new Object[]{
                rs.getString("id"),
                rs.getString("Nombre"),
                rs.getString("Nombre_Empresa")
               
            });

            
        }

       

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, e.getMessage());
    }
   
   }
