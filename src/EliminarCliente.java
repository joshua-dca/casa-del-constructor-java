    public void cargarCliente(){
    DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("Id");
    modelo.addColumn("Nombre");
    modelo.addColumn("Dirección");
    modelo.addColumn("Teléfono");
    modelo.addColumn("Correo");
    
    
    TablaCliente.setModel(modelo);  
    
     try {
        Connection con = Conexion.conectar();
        String sql = "SELECT id_cliente, nombre_cliente,dirección_cliente, telefono_cliente ,correo_cliente FROM clientes";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while (rs.next()) {
            Object[] fila = new Object[5];
            fila[0] = rs.getInt("id_cliente");
            fila[1] = rs.getString("nombre_cliente");
            fila[2] = rs.getString("dirección_cliente");
            fila[3] = rs.getString("telefono_cliente");
            fila[4]= rs.getString("correo_cliente");
           
            modelo.addRow(fila);
        }

        con.close();

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al cargar clientes: " + e.getMessage());
    }
     
    }
