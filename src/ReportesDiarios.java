private void generarReporte() {

   DefaultTableModel modelo = new DefaultTableModel();
    modelo.addColumn("ID");
    modelo.addColumn("Fecha");
    modelo.addColumn("Cliente");
    modelo.addColumn("Productos (Cant)");
    modelo.addColumn("Total");
    TablaReporte.setModel(modelo);

    try{
        Connection con = Conexion.conectar();

     String sql = "SELECT v.id_ventas, v.Fechas, c.nombre_cliente, " +
                     "GROUP_CONCAT(CONCAT(p.nombre, ' (', dv.cantidad, ')') SEPARATOR ', ') AS detalle_productos, " +
                     "SUM(dv.cantidad * dv.precio_unitario) AS total_venta " +
                     "FROM ventas v " +
                     "INNER JOIN clientes c ON v.id_cliente = c.id_cliente " +
                     "INNER JOIN detalle_ventas dv ON v.id_ventas = dv.id_ventas " +
                     "INNER JOIN productos p ON dv.id_producto = p.id_producto " +
                     "GROUP BY v.id_ventas";
        PreparedStatement ps = con.prepareStatement(sql);
        ResultSet rs = ps.executeQuery();

        while(rs.next()){
            Object[] fila = new Object[5];

            fila[0] = rs.getInt("id_ventas");
            fila[1] = rs.getString("Fechas");
            fila[2] = rs.getString("nombre_cliente");
            fila[3] = rs.getString("detalle_productos");
            fila[4] = rs.getDouble("total_venta");

            modelo.addRow(fila);
        }

        con.close();

    }catch(Exception e){
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }
}
